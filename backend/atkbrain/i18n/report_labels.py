def apply_shell_chrome(html: str, lang: str | None = None) -> str:
    loc = normalize_locale(lang)
    html = html.replace('lang="zh-CN"', f'lang="{lab("html_lang", loc)}"', 1)
    html = html.replace("授权渗透测试交付报告", lab("brand", loc))
    pairs = [
        ("执行摘要", "sec01", "Executive Summary", "sec01en"),
        ("漏洞统计分布", "sec02", "Severity &amp; Verification", "sec02en"),
        ("关键攻击路径", "sec03", "Attack Path", "sec03en"),
        ("资产画像", "sec04", "Assets in Scope", "sec04en"),
        ("漏洞清单总表", "sec05", "Findings Index", "sec05en"),
        ("严重漏洞", "sec06", "Critical Findings", "sec06en"),
        ("高危漏洞", "sec07", "High Findings", "sec07en"),
        ("中危漏洞", "sec08", "Medium Findings", "sec08en"),
        ("低危漏洞", "sec09", "Low Findings", "sec09en"),
    ]
    for zh, zk, en_html, ek in pairs:
        html = html.replace(f"<h2>{zh}</h2>", f"<h2>{lab(zk, loc)}</h2>")
        en_lab = lab(ek, loc)
        if loc == "en":
            html = html.replace(f'<span class="en">{en_html}</span>', "")
            html = html.replace(f'<span class="en">{en_html.replace("&amp;", "&")}</span>', "")
        elif en_lab:
            html = html.replace(f'<span class="en">{en_html}</span>', f'<span class="en">{en_lab}</span>')
    return html
