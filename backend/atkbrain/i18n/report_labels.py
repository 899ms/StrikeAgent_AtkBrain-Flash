def lab(key: str, lang: str | None = None, **vars) -> str:
    loc = normalize_locale(lang or get_report_lang())
    table = {**(_LABELS.get(loc) or _LABELS["zh"]), **(_CHROME.get(loc) or {})}
    text = table.get(key) or (_LABELS["zh"] | _CHROME["zh"]).get(key) or key
    if vars:
        try:
            text = text.format(**vars)
        except Exception:
            pass
    return text


